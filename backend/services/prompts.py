def build_prompt(doc_type: str, text: str, standards: list[str]) -> tuple[str, str, bool]:
    """Собирает (system_prompt, user_prompt, is_truncated) для запроса к DeepSeek.

    standards — стандарты, выбранные пользователем (подмножество 152-ФЗ/GDPR/
    ISO 27001/NIS2). Если у doc_type есть "always_active_category" (сейчас
    только у eula — темы вроде лицензионных ограничений, не привязанные ни к
    одному настоящему стандарту) — она добавляется в промпт всегда, независимо
    от выбора пользователя.

    is_truncated=True означает, что документ длиннее MAX_DOCUMENT_CHARS и не
    поместился в контекст целиком (редкий случай — очень длинные договоры
    с приложениями). Сейчас это только логируется на бэкенде: пользователю
    результат не помечается как "частичный", чтобы не подрывать доверие к
    платному анализу. Настоящее решение для таких документов — чанкинг
    (map-reduce по фрагментам документа с объединением найденных нарушений),
    это отдельная задача, use is_truncated здесь как точку для будущей
    интеграции чанкинга.
    """
    config = DOC_CONFIGS.get(doc_type, DOC_CONFIGS["contract"])

    standards = list(standards)
    always_active = config.get("always_active_category")
    if always_active and always_active not in standards:
        standards.append(always_active)

    focus_list = "\n".join(f"{i+1}. {point}" for i, point in enumerate(config["focus_points"]))
    standards_list = ", ".join(standards)

    # RAG: подкладываем реальные фрагменты закона для стандартов, которые
    # у нас проиндексированы (152-ФЗ/GDPR/NIS2 — см. services/retrieval.py).
    # ISO 27001 и т.п. сюда не попадают — для них промпт не меняется.
    rag_standards = [s for s in standards if s in INDEXED_LAWS]
    law_fragments = []
    if rag_standards:
        try:
            seen = {}
            for point in config["focus_points"]:
                for chunk in search_relevant_chunks(doc_type, rag_standards, point):
                    key = (chunk["law"], chunk["article"])
                    if key not in seen or chunk["distance"] < seen[key]["distance"]:
                        seen[key] = chunk
            law_fragments = sorted(seen.values(), key=lambda c: c["distance"])[:MAX_LAW_FRAGMENTS]
        except Exception as e:
            # Не должно ронять весь анализ — build_prompt() вызывается ДО
            # try/except вокруг call_deepseek() в ai_*.py, так что сбой здесь
            # иначе обошёл бы существующий fallback на local_analyze.
            print(f"[build_prompt] retrieval недоступен, продолжаю без RAG-фрагментов: {e}")

    if law_fragments:
        # Некоторые статьи закона (особенно 152-ФЗ) очень длинные — например,
        # ст. 19 занимает 12000+ символов. Для цитирования article модели
        # достаточно заголовка статьи и основного содержания; обрезаем
        # каждый фрагмент, чтобы 12 статей не раздували промпт до размера,
        # сравнимого с бюджетом на сам документ (см. MAX_DOCUMENT_CHARS ниже).
        MAX_FRAGMENT_CHARS = 1500
        fragments_text = "\n\n".join(
            f"[{c['law']}] {c['text'][:MAX_FRAGMENT_CHARS]}"
            + ("…" if len(c["text"]) > MAX_FRAGMENT_CHARS else "")
            for c in law_fragments
        )
        rag_block = f"""
Ниже приведены реальные фрагменты текста законов ({', '.join(rag_standards)}),
которые могут быть релевантны типовым зонам риска для этого типа документа —
используй их как источник для поля "article":

{fragments_text}
"""
        rag_rule = (
            f'- Для нарушений по стандартам {", ".join(rag_standards)}: в поле "article" указывай '
            f'ТОЛЬКО номер статьи из фрагментов выше, дословно как он там указан (например, "Статья 19" '
            f'или "Article 32"). Если ни один фрагмент не относится к найденному нарушению — укажи '
            f'"article": null, не выдумывай номер. Это правило НЕ распространяется на другие '
            f'упомянутые стандарты (например, ISO 27001) — для них по-прежнему указывай статью по своим знаниям.'
        )
    else:
        rag_block = ""
        rag_rule = ""

    # law_152_checklist (B1+B2) подключается ТОЛЬКО если пользователь выбрал
    # 152-ФЗ — часть пунктов (форма согласия с 01.09.2025, рассылки по ст. 15
    # 152-ФЗ) не имеет отношения к анализу по GDPR/ISO 27001/NIS2 в одиночку.
    law152_checklist = config.get("law_152_checklist")
    law152_standard = config.get("law_152_standard")
    law152_block = ""
    if law152_checklist and law152_standard and _standard_selected(standards, law152_standard):
        law152_block = f"\n{law152_checklist}\n"

    # quality_note (B3+B5) — не привязан к конкретному стандарту, подключается
    # всегда, если задан для doc_type (сейчас только privacy).
    quality_note = config.get("quality_note")
    quality_block = f"\n{quality_note}\n" if quality_note else ""

    delegation_note = config.get("delegation_note")
    delegation_block = f"\n{delegation_note}\n" if delegation_note else ""

    # Пояснение про метки анонимизации (fix-analysis-quality.md, часть A) —
    # общее для ВСЕХ doc_type, потому что клиентская анонимизация (см.
    # frontend/app/lib/anonymize.ts) применяется независимо от типа документа.
    # Без этого пояснения модель не знает, что, например, [EMAIL_1@domain.ru]
    # и [EMAIL_2@domain.ru] — это два РАЗНЫХ адреса (не одна и та же строка,
    # напечатанная дважды), и что сама метка означает "реквизит в документе
    # есть, просто скрыт", а не "реквизита нет".
    redaction_note = (
        "\nПеред анализом документ мог быть частично анонимизирован на стороне "
        "пользователя: реальные контакты и реквизиты заменены метками вида "
        "[EMAIL_1@domain.ru], [ТЕЛЕФОН_1], [ИНН_1], [ОГРН_1], [ОГРНИП_1], "
        "[СНИЛС_1], [ПАСПОРТ_1], [КАРТА_1]. Это ТЕХНИЧЕСКИЕ метки, а не текст "
        "документа. Правила их чтения:\n"
        "- Наличие метки означает, что соответствующий реквизит В ДОКУМЕНТЕ ЕСТЬ "
        "— не считай это отсутствием информации и не создавай по этому находку "
        "вида \"не указан email/телефон/ИНН\".\n"
        "- Одинаковый номер метки в рамках одной категории (например, оба раза "
        "[ИНН_1]) означает ОДНО И ТО ЖЕ исходное значение. Разный номер "
        "(например, [EMAIL_1@a.ru] и [EMAIL_2@b.ru]) означает РАЗНЫЕ исходные "
        "значения — в том числе если домены отличаются только поддоменом "
        "(например, www.). Если по смыслу документа два таких значения должны "
        "были быть одним и тем же контактом (например, два email оператора "
        "для обращений) — разные номера метки сами по себе являются находкой "
        "о внутреннем противоречии документа.\n"
        "- У email домен после \"@\" в метке настоящий, не анонимизирован — "
        "можешь и должен анализировать его как есть.\n"
    )

    # deepseek-chat: окно контекста 64K токенов, из них до 8К уходит под ответ
    # (у нас max_tokens=5000) — на сам документ остаётся ~55К токенов, для
    # кириллицы это ~100-150 тыс. символов. Берём с запасом на системный
    # промпт, инструкции и сам JSON-ответ модели.
    MAX_DOCUMENT_CHARS = 45000
    document_text = text[:MAX_DOCUMENT_CHARS]
    is_truncated = len(text) > MAX_DOCUMENT_CHARS

    system_prompt = (
        f"Ты — {config['role']}. Отвечай только в формате JSON, "
        "без пояснений и без markdown-обрамления (без ```)."
    )

    user_prompt = f"""
Проанализируй приложенный {config['doc_label']} по следующим ключевым пунктам:

{focus_list}
{delegation_block}{redaction_note}{quality_block}{law152_block}
Проверь применимость и соответствие следующим стандартам/законам: {standards_list}.
Если по тексту документа очевидно применим ещё какой-то стандарт из этого списка или смежный
с ним — включи его в "applicable_standards". Если какой-то из перечисленных стандартов явно
не применим к этому документу — не включай его.
{rag_block}
Текст документа:
{document_text}

Выдай ОТВЕТ ТОЛЬКО В ФОРМАТЕ JSON (без дополнительного текста, без markdown-обрамления, только чистый JSON).

Формат ответа:
{RESPONSE_JSON_EXAMPLE}

Правила:
- В "violations" перечисли ТОЛЬКО реально найденные нарушения/риски — не создавай записи для
  пунктов, которые полностью соответствуют требованиям. Если нарушений не найдено — верни
  пустой список "violations": [].
- "risk_level" — строго одно из значений: "high", "medium", "low" (на латинице, без кавычек-эмодзи).
  Если выше для конкретного пункта чек-листа или подтипа противоречия зафиксирован
  ФИКСИРОВАННЫЙ risk_level — используй его буквально. Не меняй его на основе
  собственного впечатления о серьёзности документа в целом.
- "standard" каждого нарушения должен быть одним из значений "applicable_standards".
- "article" — конкретная статья/пункт стандарта (например, "152-ФЗ, ст. 19, ч. 2" или "GDPR Art. 32(1)").
- "quote" — если нарушение о том, что формулировка в документе НЕКОРРЕКТНА (противоречит
  стандарту, двусмысленна и т.п.) — "quote" ОБЯЗАТЕЛЕН, дословная цитата из документа; без
  цитаты такое нарушение создавать нельзя. Если нарушение о том, что нужного раздела/пункта
  в документе НЕТ ВООБЩЕ — "quote": null, а "description" явно должен указывать, что это
  отсутствие, а не искажение формулировки.
- "suggested_wording" — ВСЕГДА массив строк, юридически корректный текст без канцелярита,
  готовый к вставке в документ. Если для исправления нарушения нужно добавить НЕСКОЛЬКО
  отдельных пунктов в документ (например, разные условия, которые логично разместить в
  разных местах) — перечисли их как отдельные элементы массива, а не объединяй в один блок
  текста. Если достаточно одной формулировки — массив из одного элемента, не пустая строка
  и не null.
- "action_checklist" — 3-6 коротких пунктов общего плана действий.
- Определи язык текста документа. Все текстовые поля ответа — "title",
  "description", "recommendation", "suggested_wording", "action_checklist" —
  пиши НА ТОМ ЖЕ ЯЗЫКЕ, что и сам документ (например, документ на английском
  — отвечай на английском; документ на русском — отвечай на русском).
  Исключение — "standard" и "article": названия стандартов и номера статей
  оставляй в их обычном написании независимо от языка документа (например,
  "GDPR Art. 32(1)" остаётся на английском, даже если сам документ и
  остальной ответ — на русском). Не смешивай языки внутри одного поля —
  каждое поле должно быть последовательно на одном языке.
- Если тема из списка ключевых пунктов выше по существу не регулируется ни
  одним из стандартов, перечисленных в "Проверь применимость...", — не
  создавай по ней нарушение и не притягивай его к неподходящему стандарту
  просто потому, что это единственный или один из немногих доступных.
- Перед тем как создать нарушение, где "description" обосновывает вывод
  цитатой из документа ("quote") как доказательством противоречия или
  несоответствия, — перепроверь, что процитированный текст РЕАЛЬНО
  подтверждает этот вывод, а не опровергает его или не имеет к нему
  отношения. Если цитата и вывод не согласуются между собой — не создавай
  такое нарушение.
- Находка уровня "low" или "medium" допустима ТОЛЬКО если ты можешь указать КОНКРЕТНОЕ
  требование закона/стандарта (с конкретной статьёй/пунктом в "article"), которому документ
  не соответствует. Замечание вида "формулировка могла бы быть более конкретной/подробной",
  "было бы лучше уточнить" и т.п. — САМО ПО СЕБЕ не основание для находки. Если ты не можешь
  назвать именно ту норму, которая требует большей конкретики по этому конкретному вопросу —
  не создавай находку вообще, даже если формулировка кажется тебе общей или неидеальной.
  Это правило не относится к находкам, для которых risk_level зафиксирован выше как "high" —
  для них по-прежнему действуют условия, явно описанные в соответствующем пункте чек-листа.
- Фраза с отрицанием и исключением (например, "не обрабатывает данные о
  здоровье, за исключением случаев, предусмотренных законодательством",
  "не передаёт данные третьим лицам, кроме ...") САМА ПО СЕБЕ не является
  признанием нарушения — это не доказательство того, что описанное в
  исключении действие происходит. Единственная допустимая находка по такой
  фразе — то, что сама оговорка-исключение неконкретна (не раскрыто, какие
  именно случаи или основания имеются в виду): risk_level не выше "medium",
  а title/description должны буквально отражать это как "основание/случаи
  исключения не конкретизированы", а не как "обработка/передача без
  основания" или любую другую формулировку, подразумевающую, что нарушение
  уже происходит.
- Никакой воды, только факты и конкретика.
{rag_rule}
""".strip()

    return system_prompt, user_prompt, is_truncated
