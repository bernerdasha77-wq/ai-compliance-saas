# Стандарты, которые считаются "выбранными" достаточно широко (модель иногда
# слегка меняет формулировку) — используется только для проверки условия
# подключения law_152_checklist в build_prompt, не для основного списка в
# промпте (там standards используется как есть).
def _standard_selected(standards: list[str], target: str) -> bool:
    target_l = target.strip().lower()
    return any(s.strip().lower() == target_l for s in standards)

