# Единая точка правды для промптов по всем типам документов
# (contract / eula / privacy). Раньше промпт и его текст были
# продублированы в каждом ai_*.py — теперь различается только
# DOC_CONFIGS ниже, сама сборка промпта общая.

from services.retrieval import search_relevant_chunks, INDEXED_LAWS

# Сколько максимум фрагментов закона подкладываем в промпт (см. build_prompt) —
# топ-N по всем focus_points сразу, чтобы не раздувать промпт.
MAX_LAW_FRAGMENTS = 12

DOC_CONFIGS = {
    "contract": {
        "role": "юридический AI-эксперт по комплаенсу и кибербезопасности с 15-летним опытом",
        "doc_label": "договор",
        "focus_points": [
            "Утечка данных (защита персональных данных)",
            "Контроль доступа",
            "Ответственность сторон",
            "Шифрование данных (AES-256 / TLS)",
            "Уведомление регулятора об инцидентах",
        ],
        "default_standards": ["152-ФЗ", "GDPR", "ISO 27001", "NIS2"],
    },
    "eula": {
        "role": "юридический AI-эксперт по лицензионным соглашениям (EULA) и условиям использования (Terms)",
        "doc_label": "документ (EULA / Terms)",
        "focus_points": [
            "Лицензионные ограничения",
            "Условия использования",
            "Сбор и обработка данных",
            "Ответственность и гарантии",
            "Расторжение и изменение условий",
        ],
        "default_standards": ["EULA Best Practices", "GDPR"],
        # EULA/Terms часто корректно делегируют детали в отдельную Политику
        # конфиденциальности вместо дублирования — без этой оговорки модель
        # штрафовала документ за "отсутствие" содержания, которое на самом
        # деле просто вынесено в другой документ по ссылке (см. ложные
        # срабатывания на реальном тесте: 4 из 6 находок).
        "delegation_note": (
            'ВАЖНО про пункт "Сбор и обработка данных" выше: если документ явно отсылает '
            "к отдельной Политике конфиденциальности (или аналогичному отдельному документу) "
            "за деталями — целями обработки, сроками хранения, правовым основанием, "
            "трансграничной передачей, правами субъекта данных, мерами защиты и т.п. — "
            "НЕ считай отсутствие этих деталей внутри самого EULA/Terms нарушением по этому "
            "пункту. Не дублировать содержание между документами — стандартная и корректная "
            "юридическая практика. Отмечай нарушение по теме сбора/обработки данных ТОЛЬКО "
            "если (а) отсылки на отдельный документ нет вообще, ни в каком виде, или "
            "(б) то, что фактически написано в EULA по теме, противоречит стандарту "
            "(например, сам механизм получения согласия неконкретен или недостаточен — это "
            "проблема самого EULA, а не то, что можно делегировать). Тебе НЕ показан текст "
            "самой Политики конфиденциальности — и именно поэтому не нужно строить "
            "предположения о том, что в ней может отсутствовать: сам факт корректной ссылки "
            "на неё уже закрывает вопрос по этому пункту, дальнейшая оценка её содержания "
            "не входит в анализ текущего документа. Не создавай записи в \"violations\" вида "
            '"нет информации о X" или "не указано Y", если X/Y — это как раз то, что документ '
            "явно делегировал отдельной политике."
        ),
    },
    "privacy": {
        "role": "юридический AI-эксперт по защите данных и политикам конфиденциальности",
        "doc_label": "политику конфиденциальности",
        "focus_points": [
            "Сбор и обработка данных",
            "Передача данных третьим лицам",
            "Согласие пользователя",
            "Сроки хранения данных",
            "Права субъекта данных",
        ],
        "default_standards": ["GDPR", "152-ФЗ", "ISO 27001"],
    },
}

# Единый JSON-контракт ответа модели для всех типов документов.
# risk_level значения — только "high" | "medium" | "low" (латиницей),
# чтобы бэкенду не приходилось гадать/мапить русские формулировки.
RESPONSE_JSON_EXAMPLE = """{
    "applicable_standards": ["GDPR", "152-ФЗ"],
    "violations": [
        {
            "risk_level": "high",
            "standard": "GDPR",
            "article": "Art. 32(1)",
            "title": "Короткое название нарушения",
            "description": "В чём именно проблема, со ссылкой на контекст документа",
            "quote": "конкретная фраза/раздел документа или null, если нарушение не про конкретную формулировку",
            "recommendation": "Конкретное действие по исправлению",
            "suggested_wording": "Готовый текст, который можно скопировать и вставить в документ"
        }
    ],
    "action_checklist": ["короткий пункт действия 1", "короткий пункт действия 2"]
}"""


def build_prompt(doc_type: str, text: str, law: str = "152-ФЗ") -> tuple[str, str, bool]:
    """Собирает (system_prompt, user_prompt, is_truncated) для запроса к DeepSeek.

    is_truncated=True означает, что документ длиннее MAX_DOCUMENT_CHARS и не
    поместился в контекст целиком (редкий случай — очень длинные договоры
    с приложениями). Сейчас это только логируется на бэкенде: пользователю
    результат не помечается как "частичный", чтобы не подрывать доверие к
    платному анализу. Настоящее решение для таких документов — чанкинг
    (map-reduce по фрагментам документа с объединением найденных нарушений),
    это отдельная задача, use is_truncated здесь как точку для будущей
    интеграции чанкинга.
    """
    config = DOC_CONFIGS.get(doc_type, DOC_CONFIGS["contract"])

    standards = list(config["default_standards"])
    if law and law not in standards:
        standards.insert(0, law)

    focus_list = "\n".join(f"{i+1}. {point}" for i, point in enumerate(config["focus_points"]))
    standards_list = ", ".join(standards)

    # RAG: подкладываем реальные фрагменты закона для стандартов, которые
    # у нас проиндексированы (152-ФЗ/GDPR/NIS2 — см. services/retrieval.py).
    # ISO 27001 и т.п. сюда не попадают — для них промпт не меняется.
    rag_standards = [s for s in standards if s in INDEXED_LAWS]
    law_fragments = []
    if rag_standards:
        try:
            seen = {}
            for point in config["focus_points"]:
                for chunk in search_relevant_chunks(doc_type, rag_standards, point):
                    key = (chunk["law"], chunk["article"])
                    if key not in seen or chunk["distance"] < seen[key]["distance"]:
                        seen[key] = chunk
            law_fragments = sorted(seen.values(), key=lambda c: c["distance"])[:MAX_LAW_FRAGMENTS]
        except Exception as e:
            # Не должно ронять весь анализ — build_prompt() вызывается ДО
            # try/except вокруг call_deepseek() в ai_*.py, так что сбой здесь
            # иначе обошёл бы существующий fallback на local_analyze.
            print(f"[build_prompt] retrieval недоступен, продолжаю без RAG-фрагментов: {e}")

    if law_fragments:
        # Некоторые статьи закона (особенно 152-ФЗ) очень длинные — например,
        # ст. 19 занимает 12000+ символов. Для цитирования article модели
        # достаточно заголовка статьи и основного содержания; обрезаем
        # каждый фрагмент, чтобы 12 статей не раздували промпт до размера,
        # сравнимого с бюджетом на сам документ (см. MAX_DOCUMENT_CHARS ниже).
        MAX_FRAGMENT_CHARS = 1500
        fragments_text = "\n\n".join(
            f"[{c['law']}] {c['text'][:MAX_FRAGMENT_CHARS]}"
            + ("…" if len(c["text"]) > MAX_FRAGMENT_CHARS else "")
            for c in law_fragments
        )
        rag_block = f"""
Ниже приведены реальные фрагменты текста законов ({', '.join(rag_standards)}),
которые могут быть релевантны типовым зонам риска для этого типа документа —
используй их как источник для поля "article":

{fragments_text}
"""
        rag_rule = (
            f'- Для нарушений по стандартам {", ".join(rag_standards)}: в поле "article" указывай '
            f'ТОЛЬКО номер статьи из фрагментов выше, дословно как он там указан (например, "Статья 19" '
            f'или "Article 32"). Если ни один фрагмент не относится к найденному нарушению — укажи '
            f'"article": null, не выдумывай номер. Это правило НЕ распространяется на другие '
            f'упомянутые стандарты (например, ISO 27001) — для них по-прежнему указывай статью по своим знаниям.'
        )
    else:
        rag_block = ""
        rag_rule = ""

    delegation_note = config.get("delegation_note")
    delegation_block = f"\n{delegation_note}\n" if delegation_note else ""

    # deepseek-chat: окно контекста 64K токенов, из них до 8К уходит под ответ
    # (у нас max_tokens=5000) — на сам документ остаётся ~55К токенов, для
    # кириллицы это ~100-150 тыс. символов. Берём с запасом на системный
    # промпт, инструкции и сам JSON-ответ модели.
    MAX_DOCUMENT_CHARS = 45000
    document_text = text[:MAX_DOCUMENT_CHARS]
    is_truncated = len(text) > MAX_DOCUMENT_CHARS

    system_prompt = (
        f"Ты — {config['role']}. Отвечай только в формате JSON, "
        "без пояснений и без markdown-обрамления (без ```)."
    )

    user_prompt = f"""
Проанализируй приложенный {config['doc_label']} по следующим ключевым пунктам:

{focus_list}
{delegation_block}
Проверь применимость и соответствие следующим стандартам/законам: {standards_list}.
Если по тексту документа очевидно применим ещё какой-то стандарт из этого списка или смежный
с ним — включи его в "applicable_standards". Если какой-то из перечисленных стандартов явно
не применим к этому документу — не включай его.
{rag_block}
Текст документа:
{document_text}

Выдай ОТВЕТ ТОЛЬКО В ФОРМАТЕ JSON (без дополнительного текста, без markdown-обрамления, только чистый JSON).

Формат ответа:
{RESPONSE_JSON_EXAMPLE}

Правила:
- В "violations" перечисли ТОЛЬКО реально найденные нарушения/риски — не создавай записи для
  пунктов, которые полностью соответствуют требованиям. Если нарушений не найдено — верни
  пустой список "violations": [].
- "risk_level" — строго одно из значений: "high", "medium", "low" (на латинице, без кавычек-эмодзи).
- "standard" каждого нарушения должен быть одним из значений "applicable_standards".
- "article" — конкретная статья/пункт стандарта (например, "152-ФЗ, ст. 19, ч. 2" или "GDPR Art. 32(1)").
- "quote" — конкретная цитата из документа, если нарушение привязано к формулировке; иначе null.
- "suggested_wording" — юридически корректный текст, готовый к вставке в документ, без канцелярита.
- "action_checklist" — 3-6 коротких пунктов общего плана действий.
- Никакой воды, только факты и конкретика.
{rag_rule}
""".strip()

    return system_prompt, user_prompt, is_truncated
